<h2 class="wp-block-heading">Débarrassage et nettoyage : ce qu’on nous demande avant de nous confier les clés</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Débarrassage et nettoyage en Isère : les réponses simples aux questions qu’on nous pose le plus souvent avant chaque chantier.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"d38-questions","layout":{"type":"default"}} -->
<div class="wp-block-group d38-questions"><!-- wp:details -->
<details class="wp-block-details"><summary>Peut-on vider la maison d’un défunt avant la fin de la succession ?</summary><!-- wp:paragraph -->
<p>Mieux vaut attendre. Débarrasser le logement peut valoir acceptation de la succession, dettes comprises. Parlez-en d’abord au notaire. Une fois les héritiers décidés, nous prenons le relais : visite, devis écrit, puis la maison vidée et nettoyée.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Faut-il être présent pendant le débarrassage ?</summary><!-- wp:paragraph -->
<p>Ce n’est pas obligatoire. Vous pouvez nous confier les clés : nous vous les rendons une fois le logement vidé et nettoyé.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Vous déplacez-vous pour une seule cave ou un seul grenier ?</summary><!-- wp:paragraph -->
<p>Oui. Une cave, un grenier ou un garage se vident très bien seuls, sans toucher au reste du logement.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Faites-vous aussi le nettoyage ?</summary><!-- wp:paragraph -->
<p>Oui. Après le débarrassage, nous balayons, nous dépoussiérons et nous lavons les sols, jusque dans les recoins. C’est l’idéal avant un état des lieux de sortie ou une mise en vente.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Combien de temps dure un débarrassage ?</summary><!-- wp:paragraph -->
<p>Une cave ne prend pas le temps d’une maison de quatre pièces. Lors de la visite, nous vous indiquons la durée prévue, et le jour de l’intervention est fixé avec vous.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Dans quelles communes vous déplacez-vous ?</summary><!-- wp:paragraph -->
<p>À Grenoble, dans toute l’agglomération et dans le reste de l’Isère : Échirolles, Saint-Martin-d’Hères, Fontaine, Meylan, Saint-Égrève, Seyssinet-Pariset, Sassenage, Le Pont-de-Claix, Crolles, Voiron, Vizille et les communes voisines.</p>
