<h2 class="wp-block-heading">Qu’est-ce qu’un cookie ?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Un cookie est un petit fichier qu’un site dépose dans votre navigateur. Certains sont nécessaires au fonctionnement du site. D’autres servent à compter les visites ou à afficher de la publicité : ceux-là demandent votre accord.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Ce que ce site dépose</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Aucun cookie de mesure d’audience, de publicité ou de réseau social. Le site ne charge aucun service extérieur : les polices sont hébergées avec lui, et il n’y a ni carte ni vidéo intégrée.</p>
<!-- /wp:paragraph -->

