<!-- wp:heading -->
<h2 class="wp-block-heading">Ce que nous recueillons, et pourquoi</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Quand vous demandez un devis avec le formulaire, nous recevons votre nom, votre téléphone, votre commune, votre e-mail si vous l’indiquez, et ce que vous nous dites des lieux. Ces informations servent uniquement à vous rappeler, à préparer la visite et à établir le devis. Nous les traitons parce que vous nous demandez un devis (mesure précontractuelle, article 6.1.b du RGPD).</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Nous ne les vendons pas, nous ne les louons pas, et nous ne vous envoyons ni publicité ni lettre d’information.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Pour bloquer les envois automatiques, le formulaire garde une heure une empreinte chiffrée de votre adresse IP, qui ne permet pas de la retrouver. Il compte ainsi les envois venant d’une même connexion (intérêt légitime, article 6.1.f du RGPD).</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Comme tout serveur, celui de notre hébergeur enregistre les connexions (adresse IP, date, page demandée) pour sa sécurité, pendant un an au plus.</p>
<!-- /wp:paragraph -->

